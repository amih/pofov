const DICT = { he, en };

function stored() {
  try { return localStorage.getItem(KEY); } catch { return null; }
}

let current = LANGS.includes(stored()) ? stored() : 'he';

export const lang = () => current;
export const isRtl = () => current === 'he';

export function t(key, vars = {}) {
  const v = DICT[current][key] ?? en[key] ?? key;
  return typeof v === 'function' ? v(vars) : v;
}

export function applyLang() {
  document.documentElement.lang = current;
  document.documentElement.dir = isRtl() ? 'rtl' : 'ltr';
}

export function setLang(next) {
  if (!LANGS.includes(next) || next === current) return;
  current = next;
  try { localStorage.setItem(KEY, next); } catch {}
  applyLang();
  document.dispatchEvent(new Event('pofov:lang'));
}

export const toggleLang = () => setLang(current === 'he' ? 'en' : 'he');
